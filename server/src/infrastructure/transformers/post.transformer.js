export const toDomainPost = (post) => ({
    id: post.id,
    userId: post.userId,
    type: post.type,
    parentPostId: post.parentPostId,
    subcontractGroupId: post.subcontractGroupId,
    title: post.title,
    description: post.description,
    startDate: post.startDate,
    endDate: post.endDate,
    address: post.address,
    status: post.status,
    createdAt: post.createdAt,
    images: post.images,
    latitude: post.latitude,
    longitude: post.longitude,
    isEmergency: post.isEmergency,
    emergencyExpiresAt: post.emergencyExpiresAt,
    allowsSubcontracting: post.allowsSubcontracting,
    categories: post.categories.map((pc) => ({
        id: pc.id,
        categoryId: pc.categoryId,
        name: pc.category.name,
        quantity: pc.quantity,
        filledCount: pc.filledCount,
        roleDescription: pc.roleDescription,
    })),
    isBidding: post.isBidding,
    bidWeights: post.bidWeights ?? undefined,
    materialResponsibility: post.materialResponsibility ?? undefined,
    budgetMax: post.budgetMax ?? undefined,
    user: post.user,
});
